/**
 * Turns a resolved config into the exact files and symlinks a repo should contain. Pure: no disk access.
 *
 * Output has two layers. `.agents/` is tool-neutral and always written: a plain copy of every rule, every skill's
 * files, and the cited references. Each target tool then gets what it reads natively: rule files in its own
 * frontmatter dialect, and one symlink per skill pointing back into `.agents/skills/`, so a skill exists on disk
 * exactly once. Codex reads `.agents/skills/` directly and has no rule directory of its own.
 *
 * Rendered rules carry a notice that they are generated; skills and references are copied byte for byte. The result is
 * sorted by path so the same input always produces the same plan.
 *
 * @module
 */

import { posix } from "node:path";

import { stringify } from "yaml";

import { CONFIG_FILE, LOCAL_DIR, type ResolvedConfig, type ResolvedRule, type Target } from "./config.js";
import { compareText, REFERENCE_PREFIX } from "./library.js";

/** Vendor-neutral output root. Rules, skills, and references are written here once. */
export const AGENTS_DIR = ".agents";

/** Where every skill's files are written; tool skill directories link here. */
export const SKILLS_DIR = `${AGENTS_DIR}/skills`;

/** One desired repo entry. Paths are repo-relative POSIX paths; a link target is relative to the link. */
export type PlannedEntry =
  | { readonly kind: "file"; readonly path: string; readonly content: string }
  | { readonly kind: "link"; readonly path: string; readonly target: string };

/** Every file and link the repo should hold, sorted by path. */
export type Plan = readonly PlannedEntry[];

/** Frontmatter dialect of a rendered rule. `agents` is the tool-neutral copy under `.agents/rules/`. */
export type RuleFormat = "agents" | "claude" | "cursor";

interface RuleLayout {
  readonly dir: string;
  readonly extension: string;
  readonly format: RuleFormat;
}

interface TargetLayout {
  /** Where rendered rules go; absent when the tool has no scoped rule files. */
  readonly rules?: RuleLayout;
  /** Directory that gets one symlink per skill into `.agents/skills/`; absent when the tool reads it directly. */
  readonly skills?: string;
}

/** Tool-neutral rule copies, written for every repo whatever its targets. */
export const AGENTS_RULES: RuleLayout = { dir: `${AGENTS_DIR}/rules`, extension: ".md", format: "agents" };

/** Where each target expects its files. Codex reads `.agents/skills/` itself and has no scoped rule files. */
export const TARGETS: Readonly<Record<Target, TargetLayout>> = {
  claude: { rules: { dir: ".claude/rules", extension: ".md", format: "claude" }, skills: ".claude/skills" },
  cursor: { rules: { dir: ".cursor/rules", extension: ".mdc", format: "cursor" }, skills: ".cursor/skills" },
  codex: {},
};

/** Comment placed between a rendered rule's frontmatter and body. */
export const GENERATED_NOTICE =
  `<!-- Generated by agent-toolkit; do not edit.\n` +
  `Change ${CONFIG_FILE} or ${LOCAL_DIR}/, then run agent-toolkit sync. -->`;

/** Frontmatter fields for each format. Claude and the neutral copy omit `paths` for a rule that always applies. */
const FRONTMATTER: Readonly<Record<RuleFormat, (rule: ResolvedRule) => Record<string, unknown>>> = {
  agents: pathsFrontmatter,
  claude: pathsFrontmatter,
  cursor: (rule) =>
    rule.paths.length === 0
      ? { description: rule.description, alwaysApply: true }
      : { description: rule.description, globs: rule.paths, alwaysApply: false },
};

/** Turn a resolved config into the full set of files and links the repo should contain, sorted by path. */
export function render(resolved: ResolvedConfig): Plan {
  const layouts = resolved.targets.map((target) => TARGETS[target]);
  const ruleLayouts = [AGENTS_RULES, ...layouts.flatMap((layout) => layout.rules ?? [])];
  const skillLinkDirs = layouts.flatMap((layout) => layout.skills ?? []);

  const entries: PlannedEntry[] = [
    ...ruleLayouts.flatMap((layout) =>
      resolved.rules.map((rule) =>
        plannedFile(`${layout.dir}/${rule.name}${layout.extension}`, renderRule(rule, layout.format)),
      ),
    ),
    ...resolved.skills.flatMap((skill) =>
      [...skill.files].map(([path, content]) => plannedFile(`${SKILLS_DIR}/${skill.name}/${path}`, content)),
    ),
    ...skillLinkDirs.flatMap((dir) =>
      resolved.skills.map((skill) =>
        plannedLink(`${dir}/${skill.name}`, posix.relative(dir, `${SKILLS_DIR}/${skill.name}`)),
      ),
    ),
    ...resolved.references.map((reference) => plannedFile(`${REFERENCE_PREFIX}${reference.id}`, reference.content)),
  ];

  return entries.toSorted((a, b) => compareText(a.path, b.path));
}

/** Render one rule as frontmatter in `format`'s dialect, the generated notice, and the body. */
export function renderRule(rule: ResolvedRule, format: RuleFormat): string {
  const frontmatter = stringify(FRONTMATTER[format](rule), { lineWidth: 0 });

  return `---\n${frontmatter}---\n\n${GENERATED_NOTICE}\n\n${rule.body}\n`;
}

function pathsFrontmatter(rule: ResolvedRule): Record<string, unknown> {
  return rule.paths.length === 0
    ? { description: rule.description }
    : { description: rule.description, paths: rule.paths };
}

function plannedFile(path: string, content: string): PlannedEntry {
  return { kind: "file", path, content };
}

function plannedLink(path: string, target: string): PlannedEntry {
  return { kind: "link", path, target };
}
